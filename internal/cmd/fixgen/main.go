// fixgen generates Go type files from AIXM XSD schemas.
//
// Usage:
//
//	go run ./internal/cmd/fixgen -xsd <xsd-file> -out <output-go-file> -pkg <package>
package main

import (
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"
	"text/template"
)

// xsdSchema is the minimal XSD structure we need to parse.
type xsdSchema struct {
	ComplexTypes []xsdComplexType `xml:"complexType"`
	SimpleTypes  []xsdSimpleType  `xml:"simpleType"`
}

type xsdComplexType struct {
	Name          string         `xml:"name,attr"`
	SimpleContent *xsdSimpleContent `xml:"simpleContent"`
	ComplexContent *xsdComplexContent `xml:"complexContent"`
}

type xsdSimpleContent struct {
	Extension *xsdExtension `xml:"extension"`
}

type xsdComplexContent struct {
	Extension *xsdExtension `xml:"extension"`
}

type xsdExtension struct {
	Base       string         `xml:"base,attr"`
	Attributes []xsdAttribute `xml:"attribute"`
	Sequence   *xsdSequence   `xml:"sequence"`
}

type xsdSequence struct {
	Elements []xsdElement `xml:"element"`
}

type xsdElement struct {
	Name      string `xml:"name,attr"`
	Type      string `xml:"type,attr"`
	MinOccurs string `xml:"minOccurs,attr"`
	MaxOccurs string `xml:"maxOccurs,attr"`
	Nillable  string `xml:"nillable,attr"`
}

type xsdAttribute struct {
	Name string `xml:"name,attr"`
	Type string `xml:"type,attr"`
	Use  string `xml:"use,attr"`
}

type xsdSimpleType struct {
	Name string `xml:"name,attr"`
}

// typeInfo is the normalized description of a type to generate.
type typeInfo struct {
	Name      string // Go type name
	IsNilable bool   // has nilReason attribute (simple value + nilReason)
	BaseType  string // underlying Go base type (string for most AIXM types)
}

var datatypesTemplate = template.Must(template.New("datatypes").Parse(`// Code generated by fixgen. DO NOT EDIT.

package {{.Package}}

// NilableString is the base for all AIXM nillable string types.
// Value holds the string content; NilReason is set when the element is xsi:nil.
type NilableString struct {
	Value     string ` + "`" + `xml:",chardata"` + "`" + `
	NilReason string ` + "`" + `xml:"nilReason,attr,omitempty"` + "`" + `
	// UOM is the unit of measure of value types (uom attribute), e.g. FT, FL,
	// M, NM or MHZ.  Empty for code and text types.
	UOM string ` + "`" + `xml:"uom,attr,omitempty"` + "`" + `
}

{{range .Types}}// {{.Name}} is an AIXM data type.
type {{.Name}} = NilableString

{{end}}
// XHTMLType holds arbitrary XHTML content as raw bytes.
type XHTMLType struct {
	Inner []byte ` + "`" + `xml:",innerxml"` + "`" + `
}
`))

func main() {
	xsdFile := flag.String("xsd", "", "Input XSD file")
	outFile := flag.String("out", "", "Output Go file")
	pkg := flag.String("pkg", "types", "Package name")
	flag.Parse()

	if *xsdFile == "" || *outFile == "" {
		flag.Usage()
		os.Exit(1)
	}

	data, err := os.ReadFile(*xsdFile)
	if err != nil {
		fmt.Fprintf(os.Stderr, "fixgen: read xsd: %v\n", err)
		os.Exit(1)
	}

	var schema xsdSchema
	if err := xml.Unmarshal(data, &schema); err != nil {
		fmt.Fprintf(os.Stderr, "fixgen: parse xsd: %v\n", err)
		os.Exit(1)
	}

	var types []typeInfo
	for _, ct := range schema.ComplexTypes {
		if ct.Name == "XHTMLType" {
			continue
		}
		if ct.SimpleContent != nil && ct.SimpleContent.Extension != nil {
			hasNilReason := false
			for _, attr := range ct.SimpleContent.Extension.Attributes {
				if attr.Name == "nilReason" {
					hasNilReason = true
					break
				}
			}
			if hasNilReason {
				types = append(types, typeInfo{
					Name:      ct.Name,
					IsNilable: true,
					BaseType:  "string",
				})
			}
		}
	}

	var sb strings.Builder
	if err := datatypesTemplate.Execute(&sb, map[string]any{
		"Package": *pkg,
		"Types":   types,
	}); err != nil {
		fmt.Fprintf(os.Stderr, "fixgen: template: %v\n", err)
		os.Exit(1)
	}

	formatted, err := format.Source([]byte(sb.String()))
	if err != nil {
		// Write unformatted so the user can debug
		_ = os.WriteFile(*outFile, []byte(sb.String()), 0644)
		fmt.Fprintf(os.Stderr, "fixgen: format: %v\n", err)
		os.Exit(1)
	}

	if err := os.WriteFile(*outFile, formatted, 0644); err != nil {
		fmt.Fprintf(os.Stderr, "fixgen: write: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("fixgen: wrote %s (%d types)\n", *outFile, len(types))
}
